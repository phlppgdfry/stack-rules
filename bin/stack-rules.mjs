#!/usr/bin/env node
// stack-rules CLI: copy curated AI coding rules into a project.
// Zero dependencies on purpose: `npx github:phlppgdfry/stack-rules` must work
// without an install step and without trusting a dependency tree.

import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, realpathSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createInterface } from "node:readline/promises";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const STACKS_DIR = join(ROOT, "stacks");

// Every format is generated from the same CLAUDE.md source, so the files can never drift apart.
export const FORMATS = {
  claude: { file: "CLAUDE.md", label: "Claude Code" },
  agents: { file: "AGENTS.md", label: "Codex, Jules, Amp and other AGENTS.md readers" },
  cursor: { file: ".cursor/rules/{stack}.mdc", label: "Cursor (project rules)", perStack: true },
  copilot: { file: ".github/copilot-instructions.md", label: "GitHub Copilot" },
  windsurf: { file: ".windsurfrules", label: "Windsurf" },
};

export function listStacks() {
  return readdirSync(STACKS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(STACKS_DIR, d.name, "CLAUDE.md")))
    .map((d) => {
      const body = readFileSync(join(STACKS_DIR, d.name, "CLAUDE.md"), "utf8");
      const title = (body.match(/^#\s+(.+)$/m)?.[1] ?? d.name).replace(/\s+—\s+AI Coding Rules$/, "");
      return { id: d.name, title, lines: body.split("\n").length };
    });
}

export function readStack(id) {
  const file = join(STACKS_DIR, id, "CLAUDE.md");
  if (!existsSync(file)) {
    const known = listStacks().map((s) => s.id).join(", ");
    throw new Error(`Unknown stack "${id}". Available: ${known}`);
  }
  return readFileSync(file, "utf8").trim();
}

/** Demote every Markdown heading one level, leaving fenced code (where `#` is a comment) untouched. */
export function demoteHeadings(markdown) {
  let inFence = false;
  return markdown.split("\n").map((line) => {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    if (!inFence && /^#{1,5}\s/.test(line)) return "#" + line;
    return line;
  }).join("\n");
}

/** Merge several stacks into one document. Each stack's H1 becomes an H2 section. */
export function mergeStacks(ids) {
  if (ids.length === 1) return readStack(ids[0]) + "\n";
  const parts = ids.map((id) => {
    const body = readStack(id);
    return demoteHeadings(body);
  });
  const titles = ids.map((id) => listStacks().find((s) => s.id === id)?.title ?? id);
  return `# Project AI coding rules — ${titles.join(" + ")}\n\n` +
    `<!-- Generated by stack-rules (${ids.join(", ")}). Edit freely: this file is yours now. -->\n\n` +
    parts.join("\n\n---\n\n") + "\n";
}

export function toCursorRule(id) {
  const stack = listStacks().find((s) => s.id === id);
  return `---\ndescription: ${stack?.title ?? id} conventions (from stack-rules)\nalwaysApply: true\n---\n\n${readStack(id)}\n`;
}

export function plannedWrites(ids, formats) {
  const writes = [];
  for (const format of formats) {
    const spec = FORMATS[format];
    if (!spec) throw new Error(`Unknown format "${format}". Use: ${Object.keys(FORMATS).join(", ")}`);
    if (spec.perStack) {
      for (const id of ids) writes.push({ path: spec.file.replace("{stack}", id), content: toCursorRule(id) });
    } else {
      writes.push({ path: spec.file, content: mergeStacks(ids) });
    }
  }
  return writes;
}

function parseArgs(argv) {
  const opts = { formats: [], force: false, dir: process.cwd(), dryRun: false, positional: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--force" || a === "-f") opts.force = true;
    else if (a === "--dry-run") opts.dryRun = true;
    else if (a === "--dir") opts.dir = resolve(argv[++i]);
    else if (a.startsWith("--format=")) opts.formats.push(...a.slice(9).split(","));
    else if (a === "--format") opts.formats.push(...argv[++i].split(","));
    else if (a === "--all-formats") opts.formats.push(...Object.keys(FORMATS));
    else opts.positional.push(a);
  }
  if (opts.formats.length === 0) opts.formats = ["claude"];
  return opts;
}

const HELP = `stack-rules — curated AI coding rules per tech stack

Usage
  npx github:phlppgdfry/stack-rules list
  npx github:phlppgdfry/stack-rules show <stack>
  npx github:phlppgdfry/stack-rules add <stack> [<stack> ...] [options]

Options
  --format <list>   claude, agents, cursor, copilot, windsurf (comma separated; default: claude)
  --all-formats     write every format at once
  --dir <path>      target project (default: current directory)
  --dry-run         print what would be written, write nothing
  -f, --force       overwrite existing files without asking

Examples
  npx github:phlppgdfry/stack-rules add nextjs-app-router
  npx github:phlppgdfry/stack-rules add nextjs-app-router drizzle-orm --format claude,cursor
`;

async function confirm(question) {
  if (!process.stdin.isTTY) return false;
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const answer = await rl.question(question);
  rl.close();
  return /^y(es)?$/i.test(answer.trim());
}

export async function main(argv = process.argv.slice(2), out = console) {
  const [command, ...rest] = argv;
  const opts = parseArgs(rest);

  if (!command || command === "help" || command === "--help" || command === "-h") {
    out.log(HELP);
    return 0;
  }
  if (command === "list") {
    for (const s of listStacks()) out.log(`  ${s.id.padEnd(22)} ${s.title}`);
    return 0;
  }
  if (command === "show") {
    if (!opts.positional[0]) throw new Error("Usage: stack-rules show <stack>");
    out.log(readStack(opts.positional[0]));
    return 0;
  }
  if (command === "add") {
    if (opts.positional.length === 0) throw new Error("Name at least one stack. Run `stack-rules list`.");
    const writes = plannedWrites(opts.positional, opts.formats);
    let written = 0;
    for (const w of writes) {
      const target = join(opts.dir, w.path);
      if (opts.dryRun) {
        out.log(`would write ${w.path} (${w.content.split("\n").length} lines)`);
        continue;
      }
      if (existsSync(target) && !opts.force) {
        const ok = await confirm(`${w.path} already exists. Overwrite? [y/N] `);
        if (!ok) {
          out.log(`skipped ${w.path} (exists; use --force to overwrite)`);
          continue;
        }
      }
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, w.content);
      out.log(`✓ wrote ${w.path}`);
      written++;
    }
    if (!opts.dryRun) out.log(`\n${written} file(s) written for ${opts.positional.join(" + ")}.`);
    return 0;
  }
  throw new Error(`Unknown command "${command}". Run with --help.`);
}

// Resolve symlinks: npx runs us through node_modules/.bin/stack-rules.
const isEntry = (() => {
  try { return realpathSync(process.argv[1]) === fileURLToPath(import.meta.url); } catch { return false; }
})();
if (isEntry) {
  main().then((code) => process.exit(code)).catch((err) => {
    console.error(`stack-rules: ${err.message}`);
    process.exit(1);
  });
}
